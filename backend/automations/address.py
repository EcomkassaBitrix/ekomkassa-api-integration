_COMPILED = [(c, n, re.compile(p)) for c, n, p in REGIONS]
_CITY_REGIONS = {'77', '78', '92'}

STREET = re.compile(r'^(ул|улица|пр-кт|пр|просп|проспект|пер|переулок|ш|шоссе|б-р|бульвар|наб|набережная|пл|площадь|проезд|туп|тупик|аллея|тракт|мкр|микрорайон|линия|проулок)\.?(\s|$)', re.I)
LOCALITY = re.compile(r'^(г|гор|город|пгт|рп|п|пос|поселок|посёлок|с|село|дер|деревня|ст-ца|станица|х|хутор|аул|нп|снт|тер)\.?\s+[^\d\s]', re.I)
HOUSE = re.compile(r'^(?:(?:д|дом|вл|влд|домовладение)\.?\s*)?(\d+[а-яa-z]?(?:\s?[/-]\s?\d+[а-яa-z]?)?)$', re.I)
BUILDING = re.compile(r'^(?:корп/стр|корп|корпус|к|стр|строение|литера|лит|сооружение|соор)\.?\s*:?\s*(.+)$', re.I)
OFFICE = re.compile(r'^(?:офис/кв|оф|офис|кв|квартира|пом|помещение|помещ|комн|комната|ком)\.?\s*:?\s*(.+)$', re.I)
POSTAL = re.compile(r'^\d{6}$')


def find_region(text):
    low = str(text or '').lower().replace('ё', 'е')
    for code, name, rx in _COMPILED:
        if rx.search(low):
            return code, name
    return '', ''


def parse_address(text):
    out = {}
    raw = ' '.join(str(text or '').split())
    if not raw:
        return out
    segs = [s.strip() for s in re.split(r'[,;]', raw) if s.strip()]
    rest = []
    for s in segs:
        if POSTAL.match(s) and 'PostalCode' not in out:
            out['PostalCode'] = s
        else:
            rest.append(s)
    code, name = find_region(raw)
    if code:
        out['RegionCode'], out['Region'] = code, name
    used = set()
    for i, s in enumerate(rest):
        low = s.lower().replace('ё', 'е')
        if code and any(rx.search(low) for c, n, rx in _COMPILED if c == code) and not LOCALITY.match(s) and not STREET.match(s) and code not in _CITY_REGIONS:
            used.add(i)
    for i, s in enumerate(rest):
        if i in used:
            continue
        m_off = OFFICE.match(s)
        m_bld = BUILDING.match(s)
        m_house = HOUSE.match(s)
        if m_house and 'HouseNumber' not in out and not POSTAL.match(s):
            out['HouseNumber'] = m_house.group(1).replace(' ', '')
            used.add(i)
        elif m_off and 'Office' not in out and re.search(r'\d', m_off.group(1)):
            out['Office'] = m_off.group(1).strip() if s.lower().startswith('офис/кв') else s
            used.add(i)
        elif m_bld and 'Building' not in out and re.search(r'\d|^[а-яa-z]$', m_bld.group(1), re.I):
            out['Building'] = m_bld.group(1).strip() if s.lower().startswith('корп/стр') else s
            used.add(i)
    for i, s in enumerate(rest):
        if i in used:
            continue
        if 'Street' not in out and STREET.match(s):
            out['Street'] = s
            used.add(i)
        elif 'Settlement' not in out and LOCALITY.match(s):
            out['Settlement'] = s
            used.add(i)
    if 'Settlement' not in out and code in _CITY_REGIONS:
        for i, s in enumerate(rest):
            if i not in used and find_region(s)[0] == code:
                out['Settlement'] = s
                used.add(i)
                break
    if 'Street' not in out:
        for i, s in enumerate(rest):
            if i not in used and re.search(r'[а-яА-Я]', s) and not find_region(s)[0]:
                out['Street'] = s
                used.add(i)
                break
    if 'HouseNumber' not in out:
        m = re.search(r'(?:^|[\s,])(?:д|дом|вл|влд)\.?\s*(\d+[а-яa-z]?(?:\s?[/-]\s?\d+[а-яa-z]?)?)(?=[\s,]|$)', raw, re.I)
        if m:
            out['HouseNumber'] = m.group(1).replace(' ', '')
    return out
